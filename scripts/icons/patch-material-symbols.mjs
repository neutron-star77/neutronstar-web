	"add","arrow-forward-rounded","arrow-outward-rounded","article-outline-rounded",
	"auto-awesome-outline-rounded","block","book-2-outline-rounded",
	"bookmark-outline-rounded","calendar-month-outline-rounded","calendar-today-outline-rounded",
	"calendar-today-rounded","cancel","category-outline-rounded","chat-bubble-outline-rounded",
	"check","check-circle-outline-rounded","check-rounded","chevron-left-rounded",
	"chevron-right-rounded","close","close-rounded","code-rounded","construction-rounded",
	"content-copy-rounded","contract-rounded","dark-mode-outline-rounded",
	"deployed-code","devices-rounded","domain-rounded","download-rounded",
	"edit","edit-calendar-outline-rounded","edit-note-outline-rounded","error-outline-rounded",
	"expand-more-rounded","explore-outline-rounded","explore-rounded","fit-screen-rounded",
	"flag-rounded","folder-outline-rounded","format-list-bulleted-rounded","forum-outline-rounded",
	"fullscreen","fullscreen-rounded","grid-view-rounded","handshake-outline-rounded",
	"history-rounded","home","home-outline-rounded","image-outline-rounded",
	"inventory-2-outline-rounded","keep-rounded","keyboard-arrow-down","keyboard-arrow-down-rounded",
	"keyboard-arrow-up-rounded","key-rounded","link-rounded","live-tv-outline-rounded",
	"local-florist-outline-rounded","location-on-outline-rounded","lock-open-rounded",
	"lock","menu-rounded","more-horiz","motion-photos-paused-rounded","music-note-rounded",
	"open-in-full-rounded","open-in-new-rounded","palette-outline","pause-rounded",
	"photo-library-outline-rounded","play-arrow-rounded","progress-activity","queue-music-rounded",
	"radio-button-partial","refresh-rounded","repeat-one-rounded","repeat-rounded",
	"search","search-off-rounded","search-rounded","share",
	"shield-lock-rounded","shuffle-rounded","skip-next-rounded",
	"skip-previous-rounded","star-rounded","tag-rounded","translate","tv-off-outline-rounded",
	"update-rounded","view-list-rounded","visibility-off-rounded","visibility-outline-rounded",
	"visibility-rounded","volume-off-rounded","volume-up-rounded","wallpaper","waves-rounded",
	"wb-sunny-outline-rounded","zoom-in-rounded","zoom-out-rounded",
	// —— 导航菜单图标库（src/config/navIconLibrary.ts）同步追加 ——
	"apps-rounded","archive-outline-rounded","call-rounded","cloud-outline-rounded",
	"deployed-code-outline-rounded","favorite-outline-rounded","groups-rounded",
	"info-outline-rounded","language","library-books-outline-rounded","mail-outline-rounded",
